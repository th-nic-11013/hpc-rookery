#!/usr/bin/env python3
"""Render GLOSSARY.md from glossary/<term>.md, one file per term.

Each file holds one line, `**Term** — plain-language meaning`. GLOSSARY.md
lists them sorted by term; it is generated, so a new term is a new file,
never an edit of GLOSSARY.md, and a merge conflict there is solved by
re-rendering.

    python3 scripts/render_glossary.py           # rewrite GLOSSARY.md
    python3 scripts/render_glossary.py --check   # exit 1 if it is stale
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TERMS = ROOT / "glossary"
OUT = ROOT / "GLOSSARY.md"
LINE = re.compile(r"^\*\*(?P<term>.+?)\*\* — \S")
HEADER = ("# Glossary\n\n"
          "<!-- generated by scripts/render_glossary.py from glossary/<term>.md; do not edit -->\n\n")


def entries() -> list[str]:
    out = []
    for path in sorted(TERMS.glob("*.md")):
        text = path.read_text().strip()
        m = LINE.match(text)
        if not m or "\n" in text:
            raise ValueError(f"{path.relative_to(ROOT)}: one line, '**Term** — meaning'")
        out.append((m["term"].casefold(), text))
    return [text for _, text in sorted(out)]


def render() -> str:
    return HEADER + "".join(f"- {e}\n" for e in entries())


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if GLOSSARY.md is stale")
    a = ap.parse_args()
    new = render()
    old = OUT.read_text() if OUT.exists() else ""
    if a.check:
        if new != old:
            print("GLOSSARY.md is stale: run python3 scripts/render_glossary.py")
            return 1
        return 0
    if new != old:
        OUT.write_text(new)
        print("rendered GLOSSARY.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
